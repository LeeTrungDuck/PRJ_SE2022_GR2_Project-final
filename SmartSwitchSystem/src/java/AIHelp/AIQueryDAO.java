package AIHelp;

import enums.Role;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import utills.DBConnection;

/**
 * Executes validated, read-only query plans generated by the AI layer.
 * The AI supplies JSON metadata, never executable SQL.
 */
public class AIQueryDAO implements AutoCloseable {

    private static final int MAX_ROWS = 100;
    private static final int QUERY_TIMEOUT_SECONDS = 10;
    private static final Pattern REFERENCE = Pattern.compile(
            "(?i)\\b(USER|DEVICE|SWITCH|PERMISSION|SCHEDULE|HISTORY)\\.([A-Z_][A-Z0-9_]*)\\b");
    private static final Pattern SIMPLE_COLUMN = Pattern.compile(
            "(?i)^(USER|DEVICE|SWITCH|PERMISSION|SCHEDULE|HISTORY)\\.([A-Z_][A-Z0-9_]*)$");
    private static final Pattern AGGREGATE = Pattern.compile(
            "(?i)^(COUNT|SUM|AVG|MIN|MAX)\\(\\s*(DISTINCT\\s+)?"
                    + "((USER|DEVICE|SWITCH|PERMISSION|SCHEDULE|HISTORY)\\.([A-Z_][A-Z0-9_]*)|\\*)\\s*\\)"
                    + "(?:\\s+AS\\s+[A-Z_][A-Z0-9_]*)?$");

    private static final Map<String, TableDef> TABLES = new LinkedHashMap<>();
    private static final Set<String> ALLOWED_JOINS = new HashSet<>();

    static {
        table("USER", "tblUser", "u", "user_id", "user_name", "full_name", "role", "is_active", "email",
                "phone_number");
        table("DEVICE", "tblESP32_Device", "e", "device_id", "name", "host_name", "status", "is_active");
        table("SWITCH", "tblSwitch", "s", "switch_id", "device_id", "switch_name", "gpio_pin", "status", "is_active");
        table("PERMISSION", "tblDevice_Permission", "p", "permission_id", "user_id", "switch_id", "granted_by",
                "is_active");
        table("SCHEDULE", "tblSchedule", "sc", "schedul_id", "switch_id", "user_id", "action", "run_time", "is_enabled",
                "is_active");
        table("HISTORY", "tblControl_History", "h", "history_id", "user_id", "switch_id", "command", "result",
                "control_time");

        join("USER.user_id", "HISTORY.user_id");
        join("SWITCH.switch_id", "HISTORY.switch_id");
        join("DEVICE.device_id", "SWITCH.device_id");
        join("USER.user_id", "SCHEDULE.user_id");
        join("SWITCH.switch_id", "SCHEDULE.switch_id");
        join("USER.user_id", "PERMISSION.user_id");
        join("SWITCH.switch_id", "PERMISSION.switch_id");
    }

    private final Connection connection;

    public AIQueryDAO() throws SQLException, ClassNotFoundException {
        this(DBConnection.getConnection());
    }

    public AIQueryDAO(Connection connection) {
        this.connection = connection;
    }

    public List<Map<String, Object>> execute(AIQueryPlan plan,
            String currentUserId, Role currentRole) throws SQLException {
        QueryBuild query = build(plan, currentUserId, currentRole);
        List<Map<String, Object>> result = new ArrayList<>();
        try (PreparedStatement ps = connection.prepareStatement(query.sql)) {
            ps.setQueryTimeout(QUERY_TIMEOUT_SECONDS);
            for (int i = 0; i < query.parameters.size(); i++) {
                ps.setObject(i + 1, query.parameters.get(i));
            }
            try (ResultSet rs = ps.executeQuery()) {
                int columnCount = rs.getMetaData().getColumnCount();
                while (rs.next()) {
                    Map<String, Object> row = new LinkedHashMap<>();
                    for (int i = 1; i <= columnCount; i++) {
                        row.put(rs.getMetaData().getColumnLabel(i), rs.getObject(i));
                    }
                    result.add(row);
                }
            }
        }
        return result;
    }

    private QueryBuild build(AIQueryPlan plan, String currentUserId, Role currentRole) {
        if (plan == null || plan.getTables() == null || plan.getTables().isEmpty()) {
            throw new IllegalArgumentException("At least one table is required.");
        }
        if (currentRole == Role.VIEWER && (currentUserId == null || currentUserId.trim().isEmpty())) {
            throw new IllegalArgumentException("Viewer identity is required.");
        }

        LinkedHashSet<String> tables = normalizeTables(plan.getTables());
        List<String> selected = plan.getSelect() == null ? Collections.<String>emptyList() : plan.getSelect();
        if (selected.isEmpty()) {
            throw new IllegalArgumentException("At least one selected column is required.");
        }

        StringBuilder sql = new StringBuilder("SELECT TOP ")
                .append(safeLimit(plan.getLimit())).append(' ');
        List<String> selectParts = new ArrayList<>();
        Set<String> selectAliases = new HashSet<>();
        for (String expression : selected) {
            selectParts.add(validateSelectExpression(expression, tables, selectAliases));
        }
        sql.append(String.join(", ", selectParts));

        String first = tables.iterator().next();
        sql.append(" FROM ").append(TABLES.get(first).sqlName)
                .append(' ').append(TABLES.get(first).alias);
        Set<String> joined = new HashSet<>();
        joined.add(first);
        if (plan.getJoins() != null) {
            for (AIJoin join : plan.getJoins()) {
                String target = normalizeTable(join == null ? null : join.getTable());
                String condition = validateJoin(join == null ? null : join.getOn(), tables, joined, target);
                sql.append(" JOIN ").append(TABLES.get(target).sqlName)
                        .append(' ').append(TABLES.get(target).alias)
                        .append(" ON ").append(replaceReferences(condition));
                joined.add(target);
            }
        }
        if (!joined.containsAll(tables)) {
            throw new IllegalArgumentException("Every requested table must have a valid join.");
        }

        List<Object> parameters = new ArrayList<>();
        List<String> where = new ArrayList<>();
        if (plan.getFilters() != null) {
            for (AIFilter filter : plan.getFilters()) {
                where.add(buildFilter(filter, tables, parameters));
            }
        }
        if (tables.contains("USER")) {
            if (currentUserId == null || currentUserId.trim().isEmpty()) {
                throw new IllegalArgumentException("Authenticated user is required for user data.");
            }
            parameters.add(currentUserId);
            where.add("u.user_id = ?");
        }
        if (currentRole == Role.VIEWER) {
            where.add(buildViewerScope(tables, currentUserId, parameters));
        }
        if (!where.isEmpty()) {
            sql.append(" WHERE ").append(String.join(" AND ", where));
        }

        if (plan.getGroupBy() != null && !plan.getGroupBy().isEmpty()) {
            List<String> groups = new ArrayList<>();
            for (String group : plan.getGroupBy()) {
                groups.add(validateQualifiedColumn(group, tables));
            }
            sql.append(" GROUP BY ").append(String.join(", ", groups));
        }
        if (plan.getOrderBy() != null) {
            String orderColumn = plan.getOrderBy().getColumn();
            if (orderColumn == null
                    || (!selectAliases.contains(orderColumn.toUpperCase())
                            && !SIMPLE_COLUMN.matcher(orderColumn.trim()).matches())) {
                throw new IllegalArgumentException("Invalid order column.");
            }
            if (!selectAliases.contains(orderColumn.toUpperCase())) {
                orderColumn = validateQualifiedColumn(orderColumn, tables);
            }
            String direction = plan.getOrderBy().getDirection();
            if (direction == null || !("ASC".equalsIgnoreCase(direction) || "DESC".equalsIgnoreCase(direction))) {
                throw new IllegalArgumentException("Invalid order direction.");
            }
            sql.append(" ORDER BY ").append(orderColumn).append(' ').append(direction.toUpperCase());
        }
        return new QueryBuild(sql.toString(), parameters);
    }

    private String buildFilter(AIFilter filter, Set<String> tables, List<Object> parameters) {
        if (filter == null || !tables.contains(normalizeTable(filter.getTable()))) {
            throw new IllegalArgumentException("Filter table is not allowed.");
        }
        String table = normalizeTable(filter.getTable());
        String column = validateColumn(table, filter.getColumn());
        String operator = filter.getOperator() == null ? "" : filter.getOperator().trim().toUpperCase();
        if (!(Arrays.asList("=", "<>", "!=", ">", ">=", "<", "<=", "LIKE", "BETWEEN").contains(operator))) {
            throw new IllegalArgumentException("Filter operator is not allowed.");
        }
        if ("BETWEEN".equals(operator)) {
            String second = filter.getSecondValue();
            if ("CURRENT_MONTH".equalsIgnoreCase(filter.getValue())) {
                parameters.add(Timestamp.valueOf(LocalDate.now().withDayOfMonth(1).atStartOfDay()));
                parameters.add(Timestamp.valueOf(LocalDate.now().withDayOfMonth(1).plusMonths(1).atStartOfDay()));
            } else {
                if (filter.getValue() == null || second == null) {
                    throw new IllegalArgumentException("BETWEEN requires two values.");
                }
                parameters.add(filter.getValue());
                parameters.add(second);
            }
            return TABLES.get(table).alias + "." + column + " BETWEEN ? AND ?";
        }
        if (filter.getValue() == null) {
            throw new IllegalArgumentException("Filter value is required.");
        }
        parameters.add(filter.getValue());
        return TABLES.get(table).alias + "." + column + " " + operator + " ?";
    }

    private String buildViewerScope(Set<String> tables, String userId, List<Object> parameters) {
        if (tables.contains("HISTORY")) {
            parameters.add(userId);
            return "EXISTS (SELECT 1 FROM tblDevice_Permission vp "
                    + "JOIN tblSwitch vs ON vs.switch_id = h.switch_id "
                    + "JOIN tblESP32_Device ve ON ve.device_id = vs.device_id "
                    + "WHERE vp.user_id = ? AND vp.switch_id = h.switch_id "
                    + "AND vp.is_active = 1 AND vs.is_active = 1 AND ve.is_active = 1)";
        }
        if (tables.contains("SCHEDULE")) {
            parameters.add(userId);
            return "EXISTS (SELECT 1 FROM tblDevice_Permission vp "
                    + "JOIN tblSwitch vs ON vs.switch_id = sc.switch_id "
                    + "JOIN tblESP32_Device ve ON ve.device_id = vs.device_id "
                    + "WHERE vp.user_id = ? AND vp.switch_id = sc.switch_id "
                    + "AND vp.is_active = 1 AND vs.is_active = 1 AND ve.is_active = 1)";
        }
        if (tables.contains("PERMISSION")) {
            parameters.add(userId);
            return "p.user_id = ? AND p.is_active = 1";
        }
        if (tables.contains("SWITCH")) {
            parameters.add(userId);
            return "EXISTS (SELECT 1 FROM tblDevice_Permission vp "
                    + "WHERE vp.user_id = ? AND vp.switch_id = s.switch_id AND vp.is_active = 1)";
        }
        if (tables.contains("DEVICE")) {
            parameters.add(userId);
            return "EXISTS (SELECT 1 FROM tblDevice_Permission vp "
                    + "JOIN tblSwitch vs ON vs.switch_id = vp.switch_id "
                    + "WHERE vp.user_id = ? AND vs.device_id = e.device_id "
                    + "AND vp.is_active = 1 AND vs.is_active = 1)";
        }
        // A viewer asking only for their own user row must not see other users.
        if (tables.contains("USER")) {
            parameters.add(userId);
            return "u.user_id = ?";
        }
        throw new IllegalArgumentException("Viewer scope cannot be applied.");
    }

    private String validateSelectExpression(String expression, Set<String> tables, Set<String> aliases) {
        if (expression == null || expression.trim().isEmpty()
                || expression.contains(";") || expression.contains("--") || expression.contains("/*")) {
            throw new IllegalArgumentException("Invalid select expression.");
        }
        String value = expression.trim();
        Matcher references = REFERENCE.matcher(value);
        boolean hasReference = false;
        while (references.find()) {
            hasReference = true;
            validateColumn(references.group(1), references.group(2));
            if (!tables.contains(references.group(1).toUpperCase())) {
                throw new IllegalArgumentException("Select table was not requested.");
            }
        }
        if (!hasReference || !(SIMPLE_COLUMN.matcher(value).matches() || AGGREGATE.matcher(value).matches())) {
            throw new IllegalArgumentException("Select expression is not allowed.");
        }
        Matcher alias = Pattern.compile("(?i)\\s+AS\\s+([A-Z_][A-Z0-9_]*)$").matcher(value);
        if (alias.find()) {
            aliases.add(alias.group(1).toUpperCase());
        }
        return replaceReferences(value);
    }

    private String validateQualifiedColumn(String expression, Set<String> tables) {
        Matcher matcher = SIMPLE_COLUMN.matcher(expression == null ? "" : expression.trim());
        if (!matcher.matches() || !tables.contains(matcher.group(1).toUpperCase())) {
            throw new IllegalArgumentException("Qualified column is not allowed.");
        }
        return TABLES.get(matcher.group(1).toUpperCase()).alias + "."
                + validateColumn(matcher.group(1), matcher.group(2));
    }

    private String validateColumn(String table, String column) {
        TableDef definition = TABLES.get(table.toUpperCase());
        if (definition == null || column == null || !definition.columns.contains(column.toLowerCase())) {
            throw new IllegalArgumentException("Column is not allowed.");
        }
        return column.toLowerCase();
    }

    private String validateJoin(String rawOn, Set<String> tables, Set<String> joined, String target) {
        if (!tables.contains(target) || rawOn == null) {
            throw new IllegalArgumentException("Join table is not allowed.");
        }
        String normalized = normalizeJoin(rawOn);
        if (!ALLOWED_JOINS.contains(normalized)) {
            throw new IllegalArgumentException("Join relation is not allowed.");
        }
        Matcher matcher = REFERENCE.matcher(rawOn);
        Set<String> referencedTables = new HashSet<>();
        while (matcher.find()) {
            validateColumn(matcher.group(1), matcher.group(2));
            referencedTables.add(matcher.group(1).toUpperCase());
        }
        if (referencedTables.size() != 2 || !referencedTables.contains(target)
                || !joined.stream().anyMatch(referencedTables::contains)) {
            throw new IllegalArgumentException("Join order is not valid.");
        }
        return rawOn;
    }

    private LinkedHashSet<String> normalizeTables(List<String> names) {
        LinkedHashSet<String> result = new LinkedHashSet<>();
        for (String name : names) {
            result.add(normalizeTable(name));
        }
        return result;
    }

    private String normalizeTable(String name) {
        if (name == null || !TABLES.containsKey(name.trim().toUpperCase())) {
            throw new IllegalArgumentException("Table is not allowed: " + name);
        }
        return name.trim().toUpperCase();
    }

    private String replaceReferences(String expression) {
        String result = expression;
        for (TableDef table : TABLES.values()) {
            result = result.replaceAll("(?i)\\b" + table.logicalName + "\\.", table.alias + ".");
        }
        return result;
    }

    private String normalizeJoin(String join) {
        String normalized = join.replaceAll("\\s+", "").toUpperCase();
        if (ALLOWED_JOINS.contains(normalized)) {
            return normalized;
        }
        String[] sides = normalized.split("=");
        if (sides.length == 2) {
            return sides[1] + "=" + sides[0];
        }
        return normalized;
    }

    private int safeLimit(Integer requested) {
        if (requested == null || requested <= 0) {
            return MAX_ROWS;
        }
        return Math.min(requested, MAX_ROWS);
    }

    private static void table(String logical, String sqlName, String alias, String... columns) {
        TABLES.put(logical, new TableDef(logical, sqlName, alias, new HashSet<>(Arrays.asList(columns))));
    }

    private static void join(String left, String right) {
        ALLOWED_JOINS.add(left.replace(".", ".").toUpperCase() + "=" + right.toUpperCase());
    }

    @Override
    public void close() throws SQLException {
        connection.close();
    }

    private static final class TableDef {
        private final String logicalName;
        private final String sqlName;
        private final String alias;
        private final Set<String> columns;

        private TableDef(String logicalName, String sqlName, String alias, Set<String> columns) {
            this.logicalName = logicalName;
            this.sqlName = sqlName;
            this.alias = alias;
            this.columns = columns;
        }
    }

    private static final class QueryBuild {
        private final String sql;
        private final List<Object> parameters;

        private QueryBuild(String sql, List<Object> parameters) {
            this.sql = sql;
            this.parameters = parameters;
        }
    }
}
